// 글자 맵 → 게임이 쓰기 좋은 모양으로 바꾸기
// ---------------------------------------------------------------------
function parseStage(stage) {
  const height = stage.map.length;
  const width = stage.map[0].length;
  const level = {
    width, height,
    walls: [],          // walls[y][x] === true 이면 벽
    player: null,
    wkb: null,
    keys: [],
    exit: null,
    corgis: [],
    happys: []
  };
  for (let y = 0; y < height; y++) {
    const row = [];
    for (let x = 0; x < width; x++) {
      const ch = stage.map[y][x];
      row.push(ch === '#');
      if (ch === 'P') level.player = { x, y };
      else if (ch === 'W') level.wkb = { x, y };
      else if (ch === 'K') level.keys.push({ x, y });
      else if (ch === 'E') level.exit = { x, y };
      else if (ch === 'C') level.corgis.push({ x, y });
      else if (ch === 'H') level.happys.push({ x, y });
    }
    level.walls.push(row);
  }
  return level;
}

// 시작점(from)에서 갈 수 있는 모든 칸을 BFS로 찾는다 (벽은 못 지나감)
function reachableFrom(level, from) {
  const seen = new Set([from.x + ',' + from.y]);
  const queue = [from];
  while (queue.length) {
    const { x, y } = queue.shift();
    for (const [dx, dy] of [[1, 0], [-1, 0], [0, 1], [0, -1]]) {
      const nx = x + dx, ny = y + dy;
      if (nx < 0 || ny < 0 || nx >= level.width || ny >= level.height) continue;
      if (level.walls[ny][nx]) continue;
      const k = nx + ',' + ny;
      if (!seen.has(k)) { seen.add(k); queue.push({ x: nx, y: ny }); }
    }
  }
  return seen;
}

// 맵이 올바른지 검사. 문제가 있으면 문제 목록(문자열 배열)을 돌려준다.
function validateStage(stage) {
  const errors = [];
  if (!Array.isArray(stage.map) || stage.map.length < 3) return ['맵이 비어 있음'];
  const width = stage.map[0].length;
  stage.map.forEach((row, i) => {
    if (row.length !== width) errors.push(`${i}번째 줄 길이가 다름 (${row.length} ≠ ${width})`);
    if (/[^#.PWKECH]/.test(row)) errors.push(`${i}번째 줄에 모르는 기호가 있음`);
  });
  if (errors.length) return errors;

  const text = stage.map.join('');
  const count = ch => text.split(ch).length - 1;
  if (count('P') !== 1) errors.push('플레이어(P)는 정확히 1개여야 함');
  if (count('E') !== 1) errors.push('출구(E)는 정확히 1개여야 함');
  if (count('W') !== 1) errors.push('WKB(W)는 정확히 1개여야 함');
  if (count('K') !== stage.keyCount) errors.push(`열쇠 수가 다름 (맵 ${count('K')}개, 설정 ${stage.keyCount}개)`);
  if (errors.length) return errors;

  const level = parseStage(stage);
  const reach = reachableFrom(level, level.player);
  const at = p => p.x + ',' + p.y;
  level.keys.forEach(k => { if (!reach.has(at(k))) errors.push(`열쇠 (${k.x},${k.y})에 갈 수 없음`); });
  if (!reach.has(at(level.exit))) errors.push('출구에 갈 수 없음');
  if (!reach.has(at(level.wkb))) errors.push('WKB가 갇혀 있음');
  [...level.corgis, ...level.happys].forEach(m => {
    if (!reach.has(at(m))) errors.push(`(${m.x},${m.y})의 방해 캐릭터가 갇혀 있음`);
  });

  // WKB 시작 칸을 벽이라고 치고도 열쇠·출구에 갈 수 있어야 한다 (유일한 통로를 막고 서 있으면 안 됨)
  level.walls[level.wkb.y][level.wkb.x] = true;
  const reachNoWkb = reachableFrom(level, level.player);
  level.walls[level.wkb.y][level.wkb.x] = false;
  if ([...level.keys, level.exit].some(p => !reachNoWkb.has(at(p)))) {
    errors.push('WKB 시작 위치가 열쇠/출구로 가는 유일한 길을 막고 있음');
  }
  return errors;
}

// 페이지가 열릴 때 모든 스테이지를 한 번씩 검사해서 콘솔에 알려준다
STAGES.forEach(s => {
  const errs = validateStage(s);
  if (errs.length) console.error(`[스테이지 ${s.id} 오류]`, errs);
});
